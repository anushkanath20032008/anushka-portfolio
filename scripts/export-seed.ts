// Generates supabase/seed.sql from the bundled snapshot so the database and the offline fallback never drift.
// Run: npm run seed
import { writeFileSync, mkdirSync } from 'node:fs';
import { SNAPSHOT as S } from '../src/data/snapshot';

const q = (v: unknown) => (v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v ?? {}))}::jsonb`;

const out: string[] = ['-- Generated by scripts/export-seed.ts. Do not edit by hand.', 'begin;'];

out.push(
  'truncate public.entries, public.folders, public.metrics, public.now_items, public.skills, public.profile restart identity cascade;',
);

const p = S.profile;
out.push(
  `insert into public.profile (id, name, headline, positioning, summary, email, linkedin, instagram, github, location, resume_url) values (1, ${q(p.name)}, ${q(p.headline)}, ${q(p.positioning)}, ${q(p.summary)}, ${q(p.email)}, ${q(p.linkedin)}, ${q(p.instagram)}, ${q(p.github)}, ${q(p.location)}, ${q(p.resumeUrl)});`,
);

for (const f of S.folders)
  out.push(`insert into public.folders (slug, label, icon_key, sort, source) values (${q(f.slug)}, ${q(f.label)}, ${q(f.iconKey)}, ${f.sort}, ${q(f.source)});`);

for (const e of S.entries)
  out.push(
    `insert into public.entries (id, folder_slug, slug, title, org, role, period, location, kind, status, sort, body) values (${q(e.id)}, ${q(e.folder)}, ${q(e.slug)}, ${q(e.title)}, ${q(e.org)}, ${q(e.role)}, ${q(e.period)}, ${q(e.location)}, ${q(e.kind)}, ${q(e.status)}, ${e.sort}, ${j(e.body)});`,
  );

S.metrics.forEach((m, i) =>
  out.push(`insert into public.metrics (label, value, sublabel, sort) values (${q(m.label)}, ${q(m.value)}, ${q(m.sublabel)}, ${i + 1});`),
);

S.now.forEach((n, i) =>
  out.push(
    `insert into public.now_items (id, label, short_label, kind, status_text, progress, detail, sort) values (${q(n.id)}, ${q(n.label)}, ${q(n.short)}, ${q(n.kind)}, ${q(n.statusText)}, ${n.progress ?? 'null'}, ${q(n.detail)}, ${i + 1});`,
  ),
);

S.skills.forEach((s, i) => out.push(`insert into public.skills ("group", name, sort) values (${q(s.group)}, ${q(s.name)}, ${i + 1});`));

out.push('commit;');
mkdirSync('supabase', { recursive: true });
writeFileSync('supabase/seed.sql', out.join('\n') + '\n');
console.log(`wrote supabase/seed.sql (${out.length} statements)`);
